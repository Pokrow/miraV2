# Метки, в которые заворачивается пользовательский текст перед отправкой модели.
USER_FENCE_OPEN = "##КЛИЕНТ_НАЧАЛО##"
USER_FENCE_CLOSE = "##КЛИЕНТ_КОНЕЦ##"


def fence_user_text(text: str) -> str:
    """Оборачивает текст клиента в метки данных.

    Сами метки из текста вырезаются: иначе достаточно было бы вписать
    ##КЛИЕНТ_КОНЕЦ## в вопрос, чтобы «выйти» из ограждения и дописать
    собственную инструкцию.
    """
    clean = (text or "").replace(USER_FENCE_OPEN, "").replace(USER_FENCE_CLOSE, "")
    return f"{USER_FENCE_OPEN}\n{clean}\n{USER_FENCE_CLOSE}"